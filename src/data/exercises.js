// Movement patterns, in the order the catalogue presents them.
export const PATTERNS = [
  'Poussée (dominante genou)',
  'Fentes',
  'Hinge (dominante hanche)',
  'Abduction',
  'Extension de hanche',
  'Adducteurs',
  'Mollets',
];

export const exById = (id) => EXERCISES.find((e) => e.id === id) || EXERCISES[0];

// Exercises within the thighs/glutes focus: drops calves and the entries
// reserved for an advanced audience. Pass { optionnels: true } to keep them.
export const coreExercises = ({ optionnels = false } = {}) =>
  EXERCISES.filter((e) => optionnels || !e.optionnel);

// Label for the exercises with no movement pattern — the original upper-body
// and core ones. They get a trailing group rather than being dropped, so a
// grouped list never silently loses an exercise a filter just matched.
export const UNTAGGED_GROUP = 'Haut du corps & core';

// Groups any list of exercises by movement pattern, in PATTERNS order, keeping
// only the non-empty groups. Pass the already-filtered list when the caller
// applies its own search/level/equipment filters.
export const groupByPattern = (list = EXERCISES) => {
  const groups = PATTERNS.map((pattern) => ({ pattern, exos: list.filter((e) => e.pattern === pattern) }));
  groups.push({ pattern: UNTAGGED_GROUP, exos: list.filter((e) => !e.pattern) });
  return groups.filter((g) => g.exos.length > 0);
};

// The whole catalogue, grouped. `optionnels: false` drops calves and the
// entries reserved for an advanced audience.
export const exercisesByPattern = ({ optionnels = true } = {}) =>
  groupByPattern(coreExercises({ optionnels }));
